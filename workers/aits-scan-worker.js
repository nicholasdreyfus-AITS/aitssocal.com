    + `<div style="font:700 11px Arial,sans-serif;letter-spacing:.5px;color:${sevColor(f.sev)}">${esc(f.tag)} &nbsp;<span style="color:#9ca3af;font-weight:400">· FINDING 0${i + 1}</span></div>`
