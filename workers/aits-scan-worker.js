// Deploy at workers.cloudflare.com. Set secret: ANTHROPIC_API_KEY = <your key>.
// The deployed Worker URL is the PROXY_URL used in public/scan.html.
//
// 2026-07-01 rework: the scan report is now computed deterministically in the
// page itself and renders complete without this Worker. This Worker's only
// job is the personalized ANALYST NOTE — the page shows a solid fallback note
// if this call fails, so an outage here can never blank the report again.
//
// Contract:  POST { answers: {...}, computed: { score, band, shadowLevel,
//            flags[], hours, findings[{tag, headline}] } }
//        →   200 { analystNote: "..." }   |   4xx/5xx { error: "..." }
// Legacy {messages:[...]} bodies (old scan.html) are still proxied through so
// the two sides can deploy in either order.
// ---------------------------------------------------------------------------

const MODEL = "claude-sonnet-5";

// Where full-report lead notifications go.
const NOTIFY_TO = ["gavin@aits.llc"];
const NOTIFY_CC = ["nick@aitssocal.com"];
// Must be a sender on the Resend-verified domain (see workers/README.md §Resend).
const NOTIFY_FROM = "AITS Scan <scan@aits.llc>";

const SYSTEM_PROMPT = `You are the senior analyst at AITS (Advanced Intelligent Technology Solutions), a San Diego-headquartered firm that gives small businesses an all-in-one managed technology platform for one flat monthly fee — built, tested regularly, monitored, and fixed by AITS engineers.

You are writing the "Analyst Note" on a free AI readiness & risk report a business owner just generated by answering ten questions. The deterministic findings are already on the report — your note adds the human read: what their combination of answers actually means for a business like theirs, in plain English a CEO or CFO immediately understands.

Rules:
- 3 to 5 sentences. Direct, specific, plain — no jargon, no exclamation points, no fear-mongering.
- Reference their industry and at least one concrete detail from their answers.
- Never name any software vendor or product (no ChatGPT, no CRM brand names). Say "AI tools" or "your systems."
- Do not repeat the findings verbatim — synthesize what they add up to.
- End by noting what a free 30-minute review would turn this into (a concrete plan, first automation live within 30 days). No hard sell.

Return ONLY a JSON object: {"analystNote": "..."} — no markdown fences, no other text.`;

const ALLOWED_ORIGINS = [
  "https://aits.llc",
  "https://www.aits.llc",
  "https://aitssocal.com",
  "https://www.aitssocal.com",
  "http://localhost:3000",
  "http://127.0.0.1:5500",
];

function esc(s) {
  return String(s || "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
}

async function handleLead(body, env, json) {
  const lead = body && body.lead;
  const c = body && body.computed;
  if (!lead || !lead.email || !lead.name || !c) {
    return json({ error: "Expected {lead:{name,company,email,cell}, computed, answers}" }, 400);
  }
  if (!env.RESEND_API_KEY) {
    return json({ error: "Lead email not configured (missing RESEND_API_KEY)" }, 503);
  }

  const findingsHtml = (c.findings || [])
    .map(
      (f, i) =>
        `<p style="margin:0 0 12px"><strong>${i + 1}. [${esc(f.tag)}] ${esc(f.headline)}</strong><br>${esc(f.detail)}<br><em>What to do: ${esc(f.fix)}</em></p>`,
    )
    .join("");

  const answersHtml = Object.entries(body.answers || {})
    .map(([k, v]) => `<tr><td style="padding:2px 10px 2px 0;color:#666">${esc(k)}</td><td style="padding:2px 0">${esc(Array.isArray(v) ? v.join(", ") : v)}</td></tr>`)
    .join("");

  const html = [
    `<h2 style="margin:0 0 4px">New AI Risk Scan lead</h2>`,
    `<p style="margin:0 0 16px;color:#666">Unlocked the full report on aits.llc/scan.html</p>`,
    `<table style="margin:0 0 16px;font-size:15px">`,
    `<tr><td style="padding:2px 10px 2px 0;color:#666">Name</td><td><strong>${esc(lead.name)}</strong></td></tr>`,
    `<tr><td style="padding:2px 10px 2px 0;color:#666">Company</td><td>${esc(lead.company)}</td></tr>`,
    lead.website ? `<tr><td style="padding:2px 10px 2px 0;color:#666">Website</td><td>${esc(lead.website)}</td></tr>` : '',
    `<tr><td style="padding:2px 10px 2px 0;color:#666">Email</td><td>${esc(lead.email)}</td></tr>`,
    `<tr><td style="padding:2px 10px 2px 0;color:#666">Cell phone</td><td>${esc(lead.cell)}</td></tr>`,
    lead.contact && lead.contact.length ? `<tr><td style="padding:2px 10px 2px 0;color:#666">Prefers</td><td><strong>${esc(lead.contact.join(' / '))}</strong></td></tr>` : '',
    `</table>`,
    `<p style="margin:0 0 16px"><strong>Exposure: ${esc(c.score)}/100 — ${esc(c.band)}</strong> · Shadow AI ${esc(c.shadowLevel)} · Flags: ${esc((c.flags || []).join("; ") || "none")} · Recoverable hours: ${esc(c.hours)}</p>`,
    body.pdfBase64 ? `<p style="color:#666">Full report attached as PDF.</p>` : `<h3>Findings</h3>${findingsHtml}<h3>Analyst note</h3><p><em>${esc(body.analystNote)}</em></p>`,
    `<h3 style="margin:16px 0 6px">Raw answers</h3><table style="font-size:13px">${answersHtml}</table>`,
  ].join("\n");

  const payload = {
    from: NOTIFY_FROM,
    to: NOTIFY_TO,
    cc: NOTIFY_CC,
    reply_to: lead.email,
    subject: `Scan lead: ${lead.name} — ${lead.company} (${c.band} ${c.score})`,
    html,
  };
  // Attach the PDF when the client managed to generate one (~cap 4MB base64).
  if (typeof body.pdfBase64 === "string" && body.pdfBase64.length > 100 && body.pdfBase64.length < 4_000_000) {
    const safeCompany = String(lead.company).replace(/[^a-z0-9]+/gi, "-").slice(0, 40) || "report";
    payload.attachments = [{ filename: `aits-risk-scan-${safeCompany}.pdf`, content: body.pdfBase64 }];
  }

  const resendRes = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${env.RESEND_API_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify(payload),
  });

  if (!resendRes.ok) {
    const detail = await resendRes.text().catch(() => "");
    return json({ error: "Email send failed", detail: detail.slice(0, 300) }, 502);
  }
  return json({ ok: true }, 200);
}

function extractJson(text) {
  if (!text) return null;
  const trimmed = text.trim();
  try { return JSON.parse(trimmed); } catch {}
  const fence = trimmed.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (fence) { try { return JSON.parse(fence[1].trim()); } catch {} }
  const brace = trimmed.match(/\{[\s\S]*\}/);
  if (brace) { try { return JSON.parse(brace[0]); } catch {} }
  return null;
}

export default {
  async fetch(request, env) {
    const origin = request.headers.get("Origin") || "";
    const corsOrigin = ALLOWED_ORIGINS.includes(origin) ? origin : ALLOWED_ORIGINS[0];
    const corsHeaders = {
      "Access-Control-Allow-Origin": corsOrigin,
      "Access-Control-Allow-Methods": "POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type",
    };
    const json = (body, status) =>
      new Response(JSON.stringify(body), {
        status,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });

    if (request.method === "OPTIONS") {
      return new Response(null, { status: 204, headers: corsHeaders });
    }
    if (request.method !== "POST") {
      return json({ error: "Method not allowed" }, 405);
    }

    let body;
    try {
      body = await request.json();
    } catch {
      return json({ error: "Invalid JSON body" }, 400);
    }

    // ---- POST /lead — full-report unlock: email the PDF + lead to AITS ----
    if (new URL(request.url).pathname === "/lead") {
      return handleLead(body, env, json);
    }

    // New contract: structured answers + computed report summary.
    let messages;
    let system;
    let maxTokens;
    if (body && body.answers && body.computed) {
      const a = body.answers;
      const c = body.computed;
      const findings = Array.isArray(c.findings)
        ? c.findings.map((f) => `- [${f.tag}] ${f.headline}`).join("\n")
        : "(none)";
      const user = [
        "Business profile from the scan:",
        `- Industry: ${a.industry || "Unknown"}`,
        `- Team size: ${a.size || "Unknown"}`,
        `- How customers arrive: ${a.leads || "Unknown"}`,
        `- Unanswered calls: ${a.missed || "Unknown"}`,
        `- Lead follow-up speed: ${a.followup || "Unknown"}`,
        `- Software subscriptions: ${a.subs || "Unknown"}`,
        `- Who fixes broken tech: ${a.fixes || "Unknown"}`,
        `- Employee AI use: ${a.ai || "Unknown"}`,
        `- Sensitive data handled: ${(a.data || []).join(", ") || "None reported"}`,
        `- Weekly hours on repetitive admin: ${a.busywork || "Unknown"}`,
        "",
        `Computed report: exposure score ${c.score}/100 (${c.band}), shadow AI ${c.shadowLevel}, compliance flags: ${(c.flags || []).join("; ") || "none"}, recoverable hours: ${c.hours}.`,
        "Findings already shown on the report:",
        findings,
        "",
        "Write the analyst note.",
      ].join("\n");
      messages = [{ role: "user", content: user }];
      system = SYSTEM_PROMPT;
      maxTokens = 400;
    } else if (body && Array.isArray(body.messages)) {
      // Legacy passthrough for the previous scan.html contract.
      messages = body.messages;
      system = undefined;
      maxTokens = 1000;
    } else {
      return json({ error: "Expected {answers, computed} or {messages}" }, 400);
    }

    try {
      const upstream = await fetch("https://api.anthropic.com/v1/messages", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "x-api-key": env.ANTHROPIC_API_KEY,
          "anthropic-version": "2023-06-01",
        },
        body: JSON.stringify({
          model: MODEL,
          max_tokens: maxTokens,
          ...(system ? { system } : {}),
          messages,
        }),
      });

      const data = await upstream.json();

      if (!upstream.ok || data.type === "error" || !Array.isArray(data.content)) {
        const message = (data && data.error && data.error.message) || "Upstream AI error";
        return json({ error: message }, upstream.ok ? 502 : upstream.status);
      }

      // Legacy path returns the raw Anthropic response shape.
      if (!system) {
        return json(data, 200);
      }

      const text = data.content[0] && data.content[0].text;
      const parsed = extractJson(text);
      if (!parsed || typeof parsed.analystNote !== "string") {
        return json({ error: "Could not parse analyst note" }, 502);
      }
      return json({ analystNote: parsed.analystNote }, 200);
    } catch (err) {
      return json({ error: err.message }, 500);
    }
  },
};
